-- ============================================================================
-- client_leads — ONE TABLE FOR EVERY ORBILYNK CLIENT SITE, NOT ONE PER CLIENT.
--
-- WHERE IT GOES: the Orbilynk platform project, Supabase jlezxfjmlctfakwiicep —
-- the same project that already holds `clients`. Measured 2026-11-23: the
-- organisation (dfvftmlcgkxoiojtilku) holds exactly TWO projects, trip2-spicy
-- and Sonia's. Giving Bella her own project would be a third, and every client
-- after her a fourth and a fifth. One shared table costs nothing extra, and it
-- gives Orbilynk ONE inbox across all clients, which is the product.
--
-- NOT APPLIED. An agent does not write to a database or run a migration.
-- Spicy applies this, and only then are the two env vars set on the Vercel
-- project and config/site.json integrations.leadStore flipped to "supabase".
--
-- RLS: enabled with NO policies, which is the house standard measured on
-- 2026-11-23 (Trip2 20 tables, Sonia 10, all RLS on, no policies). The server
-- reads and writes with the service key, which bypasses RLS; anon and
-- authenticated get nothing. A parent's name, email and child's age are in
-- here. It is shut by default or it is not built right.
-- ============================================================================

create table if not exists public.client_leads (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz  not null default now(),

  -- WHICH CLIENT. The slug from that site's config/site.json `client` field
  -- ("bella-friends"). This is what makes one table serve every client site.
  client       text         not null check (length(trim(client)) > 0),

  parent_name  text,
  email        text,
  phone        text,
  child_age    text,
  start_month  text,
  message      text,
  lang         text,

  -- TEST DATA CARRIES THE REAL MARKER, never a name that merely looks like one.
  qa           boolean      not null default false,

  -- Attribution, typed from day one. Trip2 learned this the expensive way:
  -- its attribution lives in a free-form details JSONB and "First source" only
  -- exists from 2026-11-03, so every earlier row is unanswerable.
  source       jsonb        not null default '{}'::jsonb,

  -- Owner workflow. seen_at is what makes "unanswered enquiry" a query and not
  -- a guess, which is how the WATCHER will find a parent nobody replied to.
  seen_at      timestamptz,
  notes        jsonb        not null default '[]'::jsonb
);

alter table public.client_leads enable row level security;

-- The admin screen's only query: this client, newest first.
create index if not exists client_leads_client_created_idx
  on public.client_leads (client, created_at desc);

-- The WATCHER's query: real enquiries nobody has opened yet.
create index if not exists client_leads_unseen_idx
  on public.client_leads (client, created_at desc)
  where seen_at is null and qa = false;

comment on table  public.client_leads is 'Enquiries from every Orbilynk client site. One row per enquiry, keyed by the client slug in its config/site.json.';
comment on column public.client_leads.qa     is 'TRUE = our own test row. The admin hides these and SAYS HOW MANY it hid.';
comment on column public.client_leads.source is 'Attribution captured at submit time (referrer, ad source, utm). Typed from day one, never inferred later.';
